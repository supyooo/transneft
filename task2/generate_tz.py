def run_font(r,size=None,bold=None,italic=None,name=None):
    if size: r.font.size=Pt(size)
    if bold is not None: r.bold=bold
    if italic is not None: r.italic=italic
    if name:
        r.font.name=name; r._element.rPr.rFonts.set(qn('w:eastAsia'),name)
def rich(p,text,size=None):
    # `code` -> моноширинный
    parts=text.split('`')
    for i,t in enumerate(parts):
        if not t: continue
        r=p.add_run(t)
        if i%2: run_font(r,size=(size or 12)-1.5,name='Courier New')
        elif size: run_font(r,size=size)
def P(text,indent=True,align=WD_ALIGN_PARAGRAPH.JUSTIFY,bold=False):
    p=d.add_paragraph(); p.alignment=align
    if indent: p.paragraph_format.first_line_indent=Cm(1.25)
    rich(p,text)
    if bold:
        for r in p.runs: r.bold=True
    return p
