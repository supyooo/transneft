def shade(cell,color):
    tcPr=cell._element.get_or_add_tcPr(); s=OxmlElement('w:shd')
    s.set(qn('w:val'),'clear'); s.set(qn('w:color'),'auto'); s.set(qn('w:fill'),color); tcPr.append(s)
def T(head,rows,widths):
    t=d.add_table(rows=1,cols=len(head)); t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.CENTER; t.autofit=False
    for i,h in enumerate(head):
        c=t.rows[0].cells[i]; c.text=''; r=c.paragraphs[0].add_run(h); run_font(r,size=10.5,bold=True); shade(c,'D9E2F3')
    for row in rows:
        cs=t.add_row().cells
        for i,v in enumerate(row):
            cs[i].text=''; rich(cs[i].paragraphs[0],v,size=10.5)
    tblPr=t._tbl.tblPr; lay=OxmlElement('w:tblLayout'); lay.set(qn('w:type'),'fixed'); tblPr.append(lay)
    for i,w in enumerate(widths): t.columns[i].width=Cm(w)
    for row in t.rows:
        for i,w in enumerate(widths):
            row.cells[i].width=Cm(w)
            for p in row.cells[i].paragraphs: p.paragraph_format.space_after=Pt(0); p.paragraph_format.line_spacing=1.0
    d.add_paragraph().paragraph_format.space_after=Pt(2)
